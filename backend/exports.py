"""Safe, readable exports for persisted macros."""

from __future__ import annotations

import json

from .schemas import LocatorSpec, Macro, Step


def _locator_expr(root: str, spec: LocatorSpec) -> str:
    if spec.strategy == "role":
        name = f", name={spec.name!r}" if spec.name is not None else ""
        exact = ", exact=True" if spec.exact else ""
        return f"{root}.get_by_role({spec.value!r}{name}{exact})"
    if spec.strategy == "label":
        exact = ", exact=True" if spec.exact else ""
        return f"{root}.get_by_label({spec.value!r}{exact})"
    if spec.strategy == "test_id":
        return f"{root}.get_by_test_id({spec.value!r})"
    if spec.strategy == "text":
        exact = ", exact=True" if spec.exact else ""
        return f"{root}.get_by_text({spec.value!r}{exact})"
    if spec.strategy == "placeholder":
        exact = ", exact=True" if spec.exact else ""
        return f"{root}.get_by_placeholder({spec.value!r}{exact})"
    return f"{root}.locator({spec.value!r})"


def _value_expr(step: Step) -> str:
    if step.value_ref:
        return f"values[{step.value_ref!r}]"
    return repr(step.value)


def python_export(macro: Macro) -> str:
    params = {parameter.name: parameter.default for parameter in macro.parameters}
    lines = [
        '"""Generated by Automata. Review side effects before running."""',
        "from __future__ import annotations",
        "",
        "import argparse",
        "import asyncio",
        "import csv",
        "import json",
        "from pathlib import Path",
        "from playwright.async_api import async_playwright",
        "",
        f"DEFAULTS = {params!r}",
        "",
        "",
        "async def run(**inputs):",
        "    values = {**DEFAULTS, **inputs}",
    ]
    for parameter in macro.parameters:
        if parameter.required and parameter.default is None:
            lines.append(f"    if values.get({parameter.name!r}) in (None, ''):")
            lines.append(f"        raise ValueError('Missing required parameter: {parameter.name}')")
    lines += [
        "    results = {}",
        "    async with async_playwright() as playwright:",
        "        browser = await playwright.chromium.launch(headless=False)",
        "        context = await browser.new_context(accept_downloads=True)",
        "        page = await context.new_page()",
    ]
    for step in macro.steps:
        lines.append(f"        # {step.id}: {step.description}")
        if step.action == "navigate":
            lines.append(f"        await page.goto({step.url!r}, wait_until='domcontentloaded', timeout={step.timeout_ms})")
        elif step.action == "screenshot":
            lines.append(f"        await page.screenshot(path={f'{step.id}.png'!r})")
        elif step.action in {"click", "fill", "clear", "select", "check", "uncheck", "press", "read", "download", "assert"}:
            locator = _locator_expr("page", step.locator) if step.locator else "page"
            if step.action == "click":
                lines.append(f"        await {locator}.click(timeout={step.timeout_ms})")
            elif step.action == "fill":
                lines.append(f"        await {locator}.fill(str({_value_expr(step)}), timeout={step.timeout_ms})")
            elif step.action == "clear":
                lines.append(f"        await {locator}.fill('', timeout={step.timeout_ms})")
            elif step.action == "select":
                lines.append(f"        await {locator}.select_option(str({_value_expr(step)}), timeout={step.timeout_ms})")
            elif step.action == "check":
                lines.append(f"        await {locator}.check(timeout={step.timeout_ms})")
            elif step.action == "uncheck":
                lines.append(f"        await {locator}.uncheck(timeout={step.timeout_ms})")
            elif step.action == "press":
                lines.append(f"        await {locator}.press({step.key!r}, timeout={step.timeout_ms})")
            elif step.action == "read":
                lines.append(f"        results[{step.output_key or 'value'!r}] = (await {locator}.inner_text()).strip()")
            elif step.action == "download":
                lines += [
                    f"        async with page.expect_download(timeout={step.timeout_ms}) as download_info:",
                    f"            await {locator}.click(timeout={step.timeout_ms})",
                    f"        await (await download_info.value).save_as({(step.filename or 'download.bin')!r})",
                ]
            elif step.action == "assert" and step.condition and step.condition.locator:
                condition_locator = _locator_expr("page", step.condition.locator)
                lines.append(f"        await {condition_locator}.wait_for(state='visible', timeout={step.timeout_ms})")
        elif step.action == "wait_for" and step.condition and step.condition.locator:
            locator = _locator_expr("page", step.condition.locator)
            state = "hidden" if step.condition.kind == "hidden" else "visible"
            lines.append(f"        await {locator}.wait_for(state={state!r}, timeout={step.timeout_ms})")
        elif step.action == "extract_records" and step.record_locator:
            row_expr = _locator_expr("page", step.record_locator)
            lines += [
                f"        rows = {row_expr}",
                "        records = []",
                "        for row_index in range(await rows.count()):",
                "            row = rows.nth(row_index)",
                "            record = {}",
            ]
            for field in step.fields:
                field_expr = _locator_expr("row", field.locator)
                if field.attribute:
                    lines.append(f"            record[{field.name!r}] = await {field_expr}.get_attribute({field.attribute!r})")
                else:
                    lines.append(f"            record[{field.name!r}] = (await {field_expr}.inner_text()).strip()")
            lines += ["            records.append(record)", f"        results[{(step.output_key or 'records')!r}] = records"]
        elif step.action == "export":
            filename = step.filename or f"{step.output_key or 'results'}.{step.export_format}"
            if step.export_format == "json":
                lines.append(f"        Path({filename!r}).write_text(json.dumps(results.get({step.output_key!r}, []), indent=2), encoding='utf-8')")
            else:
                lines += [
                    f"        export_rows = results.get({step.output_key!r}, [])",
                    f"        with Path({filename!r}).open('w', newline='', encoding='utf-8') as export_file:",
                    "            fields = sorted({key for row in export_rows for key in row}) if export_rows else ['value']",
                    "            writer = csv.DictWriter(export_file, fieldnames=fields)",
                    "            writer.writeheader()",
                    "            writer.writerows(export_rows)",
                ]
        elif step.action == "paginate" and step.pagination:
            next_expr = _locator_expr("page", step.pagination.next_locator)
            max_expr = repr(step.pagination.max_pages) if isinstance(step.pagination.max_pages, int) else f"values[{step.pagination.max_pages!r}]"
            lines += [
                f"        for _ in range(max(0, int({max_expr}) - 1)):",
                f"            next_link = {next_expr}",
                "            if not await next_link.is_visible(): break",
                "            await next_link.click()",
                "            await page.wait_for_load_state('domcontentloaded')",
            ]
    lines += [
        "        await context.close()",
        "        await browser.close()",
        "    return results",
        "",
        "",
        "if __name__ == '__main__':",
        "    parser = argparse.ArgumentParser()",
    ]
    for parameter in macro.parameters:
        lines.append(f"    parser.add_argument('--{parameter.name}', default=None)")
    lines += [
        "    args = vars(parser.parse_args())",
        "    asyncio.run(run(**{key: value for key, value in args.items() if value is not None}))",
        "",
    ]
    return "\n".join(lines)


def json_export(macro: Macro) -> str:
    return json.dumps(macro.model_dump(mode="json"), indent=2, ensure_ascii=False) + "\n"

